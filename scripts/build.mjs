// Regenerates everything that depends on the profile URL:
//   assets/qr/profile-qr.svg, assets/qr/profile-qr.png, contact.vcf, link-preview tags in index.html
// Usage:  npm install   then   node scripts/build.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rel = (p) => path.join(root, p);

// 1) Read PROFILE_URL from js/config.js (single source of truth)
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(rel("js/config.js"), "utf8"), sandbox);
const url = sandbox.window.CARD_CONFIG?.PROFILE_URL;
if (!/^https:\/\/[^\s]+$/.test(url || "")) throw new Error("PROFILE_URL in js/config.js must be an https:// address");
const base = url.endsWith("/") ? url : url + "/";
console.log("Profile URL:", url);

// 2) QR codes: high error correction (H = ~30% recoverable), 4-module quiet zone, navy on white
const qrOpts = { errorCorrectionLevel: "H", margin: 4, color: { dark: "#182954", light: "#FFFFFF" } };
fs.mkdirSync(rel("assets/qr"), { recursive: true });
const svg = await QRCode.toString(url, { ...qrOpts, type: "svg" });
fs.writeFileSync(rel("assets/qr/profile-qr.svg"), svg);
await QRCode.toFile(rel("assets/qr/profile-qr.png"), url, { ...qrOpts, width: 2048 });
await QRCode.toFile(rel("assets/qr/profile-qr-black.png"), url, { ...qrOpts, width: 2048, color: { dark: "#000000", light: "#FFFFFF" } });
fs.writeFileSync(rel("assets/qr/profile-qr-black.svg"), await QRCode.toString(url, { ...qrOpts, type: "svg", color: { dark: "#000000", light: "#FFFFFF" } }));
console.log("QR codes written (SVG + 2048px PNG, navy and black)");

// 3) vCard 3.0 (best supported by Samsung Contacts, Google Contacts and Apple Contacts)
const esc = (s) => s.replace(/\\/g, "\\\\").replace(/,/g, "\\,").replace(/;/g, "\\;").replace(/\n/g, "\\n");
// Fold lines longer than 75 octets (RFC 2426 / RFC 2425)
const fold = (line) => {
  const out = [];
  let s = line;
  out.push(s.slice(0, 75)); s = s.slice(75);
  while (s.length) { out.push(" " + s.slice(0, 74)); s = s.slice(74); }
  return out.join("\r\n");
};
