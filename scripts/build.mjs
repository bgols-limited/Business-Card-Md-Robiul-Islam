// 4) Link-preview tags in index.html (WhatsApp / LinkedIn need absolute URLs)
const meta = `<!-- build:meta (generated by scripts/build.mjs from js/config.js — do not edit by hand) -->
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="profile">
  <meta property="og:title" content="Md. Robiul Islam | Managing Director | B-GOLS Limited">
  <meta property="og:description" content="Tap. Connect. Save. Share. Digital business card of Md. Robiul Islam, B-GOLS Limited.">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${base}assets/exports/og-image.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <!-- /build:meta -->`;
const indexPath = rel("index.html");
const html = fs.readFileSync(indexPath, "utf8");
const updated = html.replace(/<!-- build:meta[\s\S]*?<!-- \/build:meta -->/, meta);
if (updated === html && !html.includes(url)) throw new Error("build:meta markers not found in index.html");
fs.writeFileSync(indexPath, updated);
console.log("index.html link-preview tags updated");
console.log("Done. Remember to bump VERSION in sw.js after changing files.");
